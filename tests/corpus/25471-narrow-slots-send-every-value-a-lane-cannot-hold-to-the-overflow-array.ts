// Every value a 32-bit lane cannot hold goes to the instance's overflow array and must round-trip exactly: 2^32, a negative, -0, NaN, a fraction, a huge
// number, a string, undefined, null, a boolean and an object, in every one of the six fields and in every position of a row (so an overflowing field
// next to a lane field never disturbs it).
class Rec {
  a: any;
  b: any;
  c: any;
  d: any;
  e: any;
  f: any;
  constructor(s: any) {
    this.a = s.a;
    this.b = s.b;
    this.c = s.c;
    this.d = s.d;
    this.e = s.e;
    this.f = s.f;
  }
  total(): any {
    return this.a + this.b + this.c + this.d + this.e + this.f;
  }
}

