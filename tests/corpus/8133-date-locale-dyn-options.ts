// toLocale*String on a Date held as any, and a typed Date with options held as any: locales and options read from dynamic values (arrays of tags, empty and invalid tags, null / undefined / primitive options, an options object of mixed value kinds).
// Compared byte-for-byte with node (ICU 78.2 / CLDR 48 locale data): every line is the formatter's answer for one
// locale x options x instant; a throw prints its name and message (V8's own).
function show(f: () => string): void {
  try {
    console.log(f());
  } catch (e) {
    const x = e as Error;
    console.log(x.name + ": " + x.message);
  }
}
