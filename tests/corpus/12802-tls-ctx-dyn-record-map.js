function load(entry) {
  return entry.ssl;
}
const registry = new Map();
function contextFor(name, entry) {
  let ctx = registry.get(entry);
  if (ctx === undefined) {
    const ssl = load(entry);
    ctx = tls.createSecureContext({ cert: ssl.cert, key: ssl.key, ca: ssl.ca });
    registry.set(entry, ctx);
  }
  return ctx;
}
