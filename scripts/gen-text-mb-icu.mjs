#!/usr/bin/env node
// Measures the multi-byte decoders of Node's ICU (the byte oracle) and writes them as C tables:
//   packages/runtime/src/scr_text_mb_icu.h
// For each family (big5, euc-kr, shift_jis): the single-byte outputs; the lead bytes (a byte that starts a valid pair);
// and for each lead and trail, the outcome: a valid pair (its code point, or a multi entry for two code points or a
// code point above U+FFFF), CONS (the error consumes both bytes), or REPROC (the error emits U+FFFD and the trail is
// read again as a fresh byte). The WHATWG index tables are NOT used for these families: ICU's tables and its
// invalid-byte rules differ from the standard (measured; the gbk/gb18030 decoders do match, and are kept).
// Usage: node scripts/gen-text-mb-icu.mjs <out.h>
import fs from "node:fs";

const [, , outPath] = process.argv;
if (!outPath) {
  console.error("usage: gen-text-mb-icu.mjs <out.h>");
  process.exit(2);
}
const FAMS = [
  { name: "big5", c: "big5" },
  { name: "euc-kr", c: "euckr" },
  { name: "shift_jis", c: "sjis" },
  // EUC-JP: its 0x8F lead is a three-byte form (JIS X 0212): the second byte pends (PEND2), the third is read from cells3
  { name: "euc-jp", c: "eucjp", three: 0x8f },
];
const FFFD = 0xfffd;
const decodeCps = (enc, bytes) => {
  try {
    return [...new TextDecoder(enc).decode(Uint8Array.from(bytes))].map((c) => c.codePointAt(0));
  } catch {
    throw new Error(`Node refused ${enc}`);
  }
};
const hex = (v, w) => "0x" + v.toString(16).toUpperCase().padStart(w, "0");
const out = [];
out.push("/* GENERATED by scripts/gen-text-mb-icu.mjs from Node's ICU decoders (the byte oracle). Do not edit by hand.");
out.push(" * Included ONLY by scr_text_mb.c (a link-gated unit). */");
out.push("#ifndef SCR_TEXT_MB_ICU_H");
out.push("#define SCR_TEXT_MB_ICU_H");
out.push("#include <stdint.h>");
out.push("/* Cell codes of a lead row: a valid pair is its code point (below 0xFFFD), or one of these. */");
out.push("#define SCR_ICU_CONS 0xFFFFu   /* U+FFFD, and both bytes are consumed */");
out.push("#define SCR_ICU_REPROC 0xFFFEu /* U+FFFD, and the trail is read again as a fresh byte */");
out.push("#define SCR_ICU_PEND2 0xFFFCu  /* a three-byte lead: the trail pends, and the third byte is read from cells3 */");
out.push("#define SCR_ICU_REPROC2 0xFFFBu /* three-byte level only: U+FFFD twice, and the third byte is read again */");
out.push("#define SCR_ICU_MULTI 0xFFFDu  /* a multi entry (two code points, or a code point above U+FFFF) */");
out.push("typedef struct ScrIcuMulti { uint16_t pos; uint8_t n; uint32_t cp[2]; } ScrIcuMulti;");
out.push("typedef struct ScrIcuFam {");
out.push("  const uint32_t *sb;            /* the single-byte output of each byte (U+FFFD for an error) */");
out.push("  const uint8_t *lead_index;     /* the row of a lead byte, 0xFF for a byte that is not a lead */");
out.push("  const uint16_t *cells;         /* rows of 256 cells, one row per lead */");
out.push("  const ScrIcuMulti *multi;      /* sorted by pos (row * 256 + trail) */");
out.push("  uint32_t nmulti;");
out.push("  const uint16_t *cells3;        /* the three-byte level (EUC-JP 0x8F only): rows of 256 cells per trail 0xA1..0xFE */");
out.push("  uint8_t lead3;                 /* the three-byte lead, 255 when the family has none */");
out.push("} ScrIcuFam;");
const report = {};
for (const fam of FAMS) {
  const sb = [];
  for (let b = 0; b < 256; b++) {
    const cps = decodeCps(fam.name, [b]);
    sb.push(cps.length === 1 ? cps[0] : (() => { throw new Error(`${fam.name} single ${b} is not one code point`); })());
  }
  // a lead: some trail changes the outcome, i.e. the pair is not the byte alone followed by the trail alone (a
  // lead whose pairs are all errors still consumes its trail, so the valid-pair test is not enough)
  const isLead = [];
  for (let b = 0; b < 256; b++) {
    let lead = false;
    for (let t = 0; t < 256 && !lead; t++) {
      const pair = decodeCps(fam.name, [b, t]).join(",");
      const split = [...decodeCps(fam.name, [b]), ...decodeCps(fam.name, [t])].join(",");
      if (pair !== split) lead = true;
    }
    isLead.push(lead);
  }
  const rows = [];
  for (let b = 0; b < 256; b++) if (isLead[b]) rows.push(b);
  const leadIndex = new Array(256).fill(0xff);
  rows.forEach((b, i) => (leadIndex[b] = i));
  const cells = [];
  const multi = [];
  const counts = { valid: 0, cons: 0, reproc: 0, multi: 0 };
  for (const lead of rows) {
    for (let t = 0; t < 256; t++) {
      const cps = decodeCps(fam.name, [lead, t]);
      const pos = leadIndex[lead] * 256 + t;
      if (fam.three === lead && t >= 0xa1 && t <= 0xfe) {
        cells.push(0xfffc);
        continue;
      }
      if (!cps.includes(FFFD)) {
        counts.valid++;
        if (cps.length === 1 && cps[0] < FFFD) cells.push(cps[0]);
        else {
          if (cps.length > 2) throw new Error("more than two code points in a pair");
          cells.push(0xfffd);
          multi.push({ pos, n: cps.length, cp: [cps[0], cps[1] ?? 0] });
          counts.multi++;
        }
        continue;
      }
      if (cps[0] !== FFFD) throw new Error(`${fam.name} ${lead} ${t}: an error does not start with U+FFFD`);
      const rest = cps.slice(1);
      if (rest.length === 0) {
        counts.cons++;
        cells.push(0xffff);
        continue;
      }
      // the trail read again on its own: its single output, or a pending lead (a lone lead at the end is U+FFFD)
      const fresh = isLead[t] ? [FFFD] : [sb[t]];
      if (rest.length === fresh.length && rest.every((c, i) => c === fresh[i])) {
        counts.reproc++;
        cells.push(0xfffe);
      } else {
        throw new Error(`${fam.name} ${lead} ${t}: unclassified outcome ${JSON.stringify(cps)}`);
      }
    }
  }
  // the three-byte level of the family's three-byte lead: cells3[(trail - 0xA1) * 256 + third]
  let cells3 = null;
  if (fam.three !== undefined) {
    cells3 = [];
    for (let t = 0xa1; t <= 0xfe; t++) {
      for (let u = 0; u < 256; u++) {
        const cps = decodeCps(fam.name, [fam.three, t, u]);
        if (!cps.includes(FFFD)) {
          if (cps.length !== 1 || cps[0] >= 0xfffc) throw new Error("three-byte valid cell outside the cell range");
          cells3.push(cps[0]);
          counts.three_valid = (counts.three_valid ?? 0) + 1;
          continue;
        }
        if (cps[0] !== FFFD) throw new Error("three-byte error does not start with U+FFFD");
        const rest = cps.slice(1);
        if (rest.length === 0) {
          cells3.push(0xffff);
          counts.three_cons = (counts.three_cons ?? 0) + 1;
          continue;
        }
        const fresh = isLead[u] ? [FFFD] : [sb[u]];
        if (rest.length === fresh.length && rest.every((c, i) => c === fresh[i])) {
          cells3.push(0xfffe);
          counts.three_reproc = (counts.three_reproc ?? 0) + 1;
        } else if (rest.length === fresh.length + 1 && rest[0] === FFFD && fresh.every((c, i) => c === rest[i + 1])) {
          // two errors (the trail, then the third byte is read again)
          cells3.push(0xfffb);
          counts.three_reproc2 = (counts.three_reproc2 ?? 0) + 1;
        } else {
          throw new Error(`three-byte ${t} ${u}: unclassified ${JSON.stringify(cps)}`);
        }
      }
    }
  }
  report[fam.name] = { leads: rows.length, ...counts, sb_entries: sb.length };
  out.push(`static const uint32_t scr_icu_${fam.c}_sb[256] = {`);
  for (let i = 0; i < 256; i += 16) out.push("  " + sb.slice(i, i + 16).map((v) => hex(v, 4)).join(", ") + ",");
  out.push("};");
  out.push(`static const uint8_t scr_icu_${fam.c}_lead[256] = {`);
  for (let i = 0; i < 256; i += 16) out.push("  " + leadIndex.slice(i, i + 16).map((v) => hex(v, 2)).join(", ") + ",");
  out.push("};");
  out.push(`static const uint16_t scr_icu_${fam.c}_cells[${cells.length}] = {`);
  for (let i = 0; i < cells.length; i += 16) out.push("  " + cells.slice(i, i + 16).map((v) => hex(v, 4)).join(", ") + ",");
  out.push("};");
  out.push(`static const ScrIcuMulti scr_icu_${fam.c}_multi[${Math.max(multi.length, 1)}] = {`);
  if (multi.length === 0) out.push("  {0, 0, {0, 0}},");
  for (const m of multi) out.push(`  {${m.pos}, ${m.n}, {${hex(m.cp[0], 4)}, ${hex(m.cp[1], 4)}}},`);
  out.push("};");
  out.push(`#define SCR_ICU_${fam.c.toUpperCase()}_MULTI ${multi.length}`);
  if (cells3) {
    out.push(`static const uint16_t scr_icu_${fam.c}_cells3[${cells3.length}] = {`);
    for (let i = 0; i < cells3.length; i += 16) out.push("  " + cells3.slice(i, i + 16).map((v) => hex(v, 4)).join(", ") + ",");
    out.push("};");
  }
  out.push(`static const ScrIcuFam scr_icu_${fam.c}_fam = {scr_icu_${fam.c}_sb, scr_icu_${fam.c}_lead, scr_icu_${fam.c}_cells, scr_icu_${fam.c}_multi, ${multi.length}, ${cells3 ? `scr_icu_${fam.c}_cells3` : "NULL"}, ${fam.three ?? 255}};`);
}
out.push("#endif");
fs.writeFileSync(outPath, out.join("\n") + "\n");
console.log(JSON.stringify(report));
