/* Regenerate the corpus suites' per-part entry files.
 *
 * vitest's pool is FILE-granular and isolates one process per file, and
 * tests inside a file run sequentially. The two corpus differentials hold
 * 57.8% of the gate's tests between them, so as single files they pinned
 * the gate's wall clock to one worker: measured on this tree, a warm
 * 12-worker gate took 1,365 s and its longest single file took 1,359 s —
 * 99.6% of the wall was llvm-differential.test.ts alone, and no worker
 * count could touch it.
 *
 * The suites therefore live in differential-suite.ts /
 * llvm-differential-suite.ts (not collected — they are not *.test.ts) and
 * are declared once per PART by the entry files this script writes. The
 * parts partition the corpus exactly (shard.ts's partOf), so the set still
 * runs every program exactly once; corpus-parts.test.ts fails if the files
 * on disk stop being exactly 1..PARTS, which is what keeps a deleted or
 * renamed entry from silently retiring an eighth of the corpus.
 *
 *   node scripts/gen-corpus-parts.mjs [parts]
 */
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const CORPUS_PARTS = Number(process.argv[2] ?? 8);

const dir = join(fileURLToPath(new URL("..", import.meta.url)), "tests/harness/corpus");
mkdirSync(dir, { recursive: true });
for (const f of readdirSync(dir)) rmSync(join(dir, f));

const suites = [
  ["differential", "defineDifferentialSuite", "../differential-suite.js", "the corpus differential"],
  ["llvm-differential", "defineLlvmDifferentialSuite", "../llvm-differential-suite.js", "the dual-backend differential"],
  ["coverage-corpus", "defineCoverageCorpusSweep", "../coverage-corpus-suite.js", "the coverage corpus sweep"],
];

for (const [stem, fn, from, what] of suites) {
  for (let i = 1; i <= CORPUS_PARTS; i++) {
    const p = String(i).padStart(2, "0");
    writeFileSync(
      join(dir, `${stem}-${p}.test.ts`),
      `/* Part ${i} of ${CORPUS_PARTS} of ${what}. GENERATED by
 * scripts/gen-corpus-parts.mjs — do not edit by hand, and do not delete one:
 * corpus-parts.test.ts fails when the set here stops being exactly 1..N. */
import { ${fn} } from "${from}";

${fn}(${i}, ${CORPUS_PARTS});
`,
    );
  }
}
console.log(`wrote ${suites.length * CORPUS_PARTS} entry files (${CORPUS_PARTS} parts each)`);
